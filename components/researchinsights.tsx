function Growth() {
  const [hi, setHi] = useState<number | null>(null)
  const W = 520, H = 250, L = 34, R = 10, T = 12, B = 26
  const x = (i: number) => L + (i / (SPAN.length - 1)) * (W - L - R)
  const y = (v: number) => T + (1 - v / niceMax) * (H - T - B)
  const pts = TOT.map((v, i) => [x(i), y(v)])
  const line = pts.map((p, i) => `${i ? 'L' : 'M'}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join(' ')
  const area = `${line} L${x(SPAN.length - 1)} ${y(0)} L${x(0)} ${y(0)} Z`
  return (
    <div className="ri-card">
      <h3>Year-wise growth</h3>
      <p>Publication output per year since {FROM}</p>
      <svg className="ri-svg" viewBox={`0 0 ${W} ${H}`} role="img" aria-label={`Publications per year, ${FROM} to ${SPAN[SPAN.length - 1]}`}>
        <defs><linearGradient id="ri-g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stopColor="#5eead4" stopOpacity=".5" /><stop offset="1" stopColor="#5eead4" stopOpacity="0" /></linearGradient></defs>
        {TICKS.map((t) => (<g key={t}><line x1={L} x2={W - R} y1={y(t)} y2={y(t)} stroke="rgba(255,255,255,.14)" strokeDasharray="3 4" /><text x={L - 6} y={y(t) + 3} fontSize="9" textAnchor="end">{t}</text></g>))}
        <path d={area} fill="url(#ri-g)" />
        <path d={line} fill="none" stroke="#5eead4" strokeWidth="2.2" strokeLinejoin="round" />
        {SPAN.map((yr, i) => (<g key={yr}>{(yr % 3 === 0 || (i === SPAN.length - 1 && (yr - 1) % 3 !== 0)) && <text x={x(i)} y={H - 8} fontSize="9" textAnchor="middle">{yr}</text>}
          <circle cx={x(i)} cy={y(TOT[i])} r={hi === yr ? 5 : 8} fill={hi === yr ? '#fff' : 'transparent'} onMouseEnter={() => setHi(yr)} onMouseLeave={() => setHi(null)} onClick={() => setHi(yr)} /></g>))}
      </svg>
      <div className="ri-tip" aria-live="polite">{hi ? `${hi}: ${nf(total(hi))} publications` : 'Select a point to see the year.'}</div>
    </div>
  )
}

function Types() {
  const R = 70, C = 2 * Math.PI * R
  const tot = insights.types.reduce((a, t) => a + (insights.typeTotals as Record<string, number>)[t], 0)
  let off = 0
  return (
    <div className="ri-card">
      <h3>Types of publication</h3>
      <p>All publications in the CV</p>
      <div className="ri-donut">
        <svg viewBox="0 0 200 200" width="190" height="190" role="img" aria-label="Publications by type">
          {insights.types.map((t) => {
            const v = (insights.typeTotals as Record<string, number>)[t]; const len = (v / tot) * C
            const el = <circle key={t} cx="100" cy="100" r={R} fill="none" stroke={COLOR[t]} strokeWidth="26" strokeDasharray={`${Math.max(0, len - 1.5)} ${C}`} strokeDashoffset={-off} transform="rotate(-90 100 100)" />
            off += len; return el
          })}
          <text x="100" y="98" textAnchor="middle" fontSize="26" fontWeight="700" style={{ fill: '#fff' }}>{nf(tot)}</text>
          <text x="100" y="116" textAnchor="middle" fontSize="10">publications</text>
        </svg>
        <ul className="ri-legend">
          {insights.types.map((t) => (<li key={t} style={{ ['--c' as string]: COLOR[t] }}><i />{LABEL[t]} <b>{nf((insights.typeTotals as Record<string, number>)[t])}</b></li>))}
        </ul>
      </div>
    </div>
  )
}

function Stacked() {
  const W = 1040, H = 280, L = 34, R = 10, T = 12, B = 26
  const bw = (W - L - R) / SPAN.length
  const y = (v: number) => T + (1 - v / niceMax) * (H - T - B)
  return (
    <div className="ri-card ri-wide">
      <h3>Annual publication output by document type</h3>
      <p>Year-by-year output split by type</p>
      <svg className="ri-svg" viewBox={`0 0 ${W} ${H}`} role="img" aria-label="Publications per year by type">
        {TICKS.map((t) => (<g key={t}><line x1={L} x2={W - R} y1={y(t)} y2={y(t)} stroke="rgba(255,255,255,.14)" strokeDasharray="3 4" /><text x={L - 6} y={y(t) + 3} fontSize="10" textAnchor="end">{t}</text></g>))}
        {SPAN.map((yr, i) => {
          let acc = 0
          return (<g key={yr}>
            {insights.types.map((t) => { const v = YT[String(yr)]?.[t] ?? 0; if (!v) return null; const y0 = y(acc), y1 = y(acc + v); acc += v
              return <rect key={t} x={L + i * bw + bw * 0.18} y={y1} width={bw * 0.64} height={y0 - y1} fill={COLOR[t]}><title>{`${yr}, ${LABEL[t]}: ${v}`}</title></rect> })}
            <text x={L + i * bw + bw / 2} y={H - 8} fontSize="10" textAnchor="middle">{yr}</text>
          </g>)
        })}
      </svg>
      <ul className="ri-legend">{insights.types.map((t) => (<li key={t} style={{ ['--c' as string]: COLOR[t] }}><i />{LABEL[t]}</li>))}</ul>
    </div>
  )
}

function CollabMap() {
  const [sel, setSel] = useState<string | null>(null)
  const c = sel ? HIT.get(sel) : null
  return (
    <div className="ri-card ri-wide">
      <h3>International research collaboration</h3>
      <p>Top {network.countryList.length} countries by number of co-authors (of {network.countries} countries in total). Select a country to see the count. Source: OpenAlex.</p>
      <svg className="ri-svg ri-map" viewBox={`0 0 ${world.w} ${world.h}`} role="img" aria-label="World map of collaborating countries">
        {world.countries.map((k) => {
          const on = HIT.has(k.n)
          return <path key={k.n} d={k.d} className={on ? (sel === k.n ? 'on sel' : 'on') : undefined} onClick={on ? () => setSel(sel === k.n ? null : k.n) : undefined}><title>{on ? `${HIT.get(k.n)!.name}: ${HIT.get(k.n)!.coAuthors} co-authors` : k.n}</title></path>
        })}
      </svg>
      <div className="ri-tip" aria-live="polite">{c ? `${c.name}: ${nf(c.coAuthors)} co-authors` : 'Select a highlighted country.'}</div>
      <ul className="ri-countries">
        {network.countryList.map((k) => {
          const key = ALIAS[k.name] ?? k.name
          return <li key={k.code}><button type="button" aria-pressed={sel === key} onClick={() => setSel(sel === key ? null : key)}>{k.name}<em>{nf(k.coAuthors)}</em></button></li>
        })}
      </ul>
    </div>
  )
}

export default function ResearchInsights() {
  return (
    <section className="ri-sec" aria-labelledby="ri-h">
      <style>{CSS}</style>
      <div className="ri-in">
        <h2 id="ri-h" className="ri-h2">Publication Insights</h2>
        <p className="ri-sub">How the research output has grown, what it is made of, and where collaborators are based.</p>
        <div className="ri-grid">
          <Growth />
          <Types />
          <Stacked />
          <CollabMap />
        </div>
      </div>
    </section>
  )
}
